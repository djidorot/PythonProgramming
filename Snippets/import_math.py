import math
from math import pi, sqrt
import math as m


# Standard Import: Requires prefixing with math.
import math
print(math.sqrt(25))  # Outputs: 5.0

# Specific Import: Import specific tools to use them directly.
print(sqrt(16))      # Outputs: 4.0
print(pi)            # Outputs: 3.141592653589793

# Alias Import: Shorten the module name for faster typing.
print(m.floor(4.7))   # Outputs: 4