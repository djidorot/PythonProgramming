# Strings: Counts the total number of characters, including spaces, punctuation, and special characters.
len("Hello World")  # Returns 11

# Lists: Counts the number of elements inside the outermost list.
len([10, 20, 30, 40])  # Returns 4

# Dictionaries: Counts the number of key-value pairs.
len({"name": "Alice", "age": 25})  # Returns 2

# Tuples & Sets: Counts the number of elements or unique items.
len((1, 2, 3))  # Returns 3

